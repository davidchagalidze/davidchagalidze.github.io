// ═════════════════════════════════════════════════════════════════════════════
// ENGINE — механика и рендер, не баланс.
// ═════════════════════════════════════════════════════════════════════════════
export const ENGINE = {
  grid: { w: RULES.gridW, h: RULES.gridH },
  /** Логический размер сцены; мир вписывается в него с сохранением пропорций. */
  view: { w: 960, h: 720 },
  /** Задержка между соплом и пятном эрозии: струя летит ~8–14 кадров при 60 fps. */
  beamDelaySec: 0.16,
  /**
 * Пятно плоское с резкой кромкой: урон по всей площади одинаков, суммарный темп
 * πr²·pressure·grade (HP/с) — как в модели SAND-1.
 */
  spotFlat: true,
  /**
   * ── Мост «модель → сетка» (единственное место перевода) ──────────────────
   * Модель считает темп по грязи: hp = π·r²·pressure·grade, и что струя всё время
   * работает по грязи. В сетке пятно того же радиуса накрывает и чистое железо
   * (доля грязи под ним ρ), а ведут его полосами, поэтому диск пятна покрывает не
   * всю площадь — работа идёт по хорде. Чтобы ЗА ОДИН ПРОХОД снималось ровно hp,
   * радиус пятна в клетках выводится из hp:
   *
   *     hp = 2·r_grid·√(1 − (s/2r_grid)²)·pressure·grade·ρ·(...)   (полоса шириной s)
   *     ⇒ r_grid = r_model · √(π / (2ρ))
   *
   * Множитель π/2 — отношение площади диска к площади, которую реально проходит
   * пятно за один проход полосой (s·χ, максимум 2r² при s = √2·r). Радиус
   * выводится из hp, а не наоборот: hp — вход (economy.mjs), ρ — свойство заказа,
   * r_grid — следствие. `ENGINE.cutAssist` — остаток, который добирается замером.
   */
  gridSpotRadius(radiusCells, dirtShare) {
    const share = Math.min(1, Math.max(0.05, Number(dirtShare) || 1));
    return radiusCells * Math.sqrt(Math.PI / (2 * share)) * (ENGINE.cutAssist || 1);
  },
  cutAssist: 1.75,
  /** Доля исходной грязи, ниже которой бот дочищает отдельными пятнами (не полосами). */
  /** Порог сдачи заказа, доля %. Модель считает 95% и 100% — между ними ловушка. */
  minDeliverPct: 95,
  /** Полное добивание до 100% даёт bonus100 и включает хвост — см. pay.mjs. */
  cleanFullPct: 99.5,
  /** Гравитация и жизнь частиц — только визуал, на урон не влияют. */
  particles: {
    max: 900,
    perKg: 900,
    gravity: 1150,
    lifeSec: [0.5, 1.15],
    spread: 0.055,
    bounce: 0.32,
    drag: 0.985,
  },
  /** Как часто писать сохранение (мс). */
  autosaveMs: 4000,
  /** Ячейка считается чистой ниже этого порога прочности. */
  cleanEpsilon: 0.002,
  /** Накладка (скрытый очаг окалины) снимается струёй за это время, с. */
  plateSec: 0.45,
  /** Шаг сетки для визуальных вмятин (тонкий лист). */
  dentCell: 4,
};

